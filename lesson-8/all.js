// 7.3 Цикл на кожній ітерації пропонує через prompt ввести число більше 100 (але максимум 10 ітерацій циклу) . Якщо відвідувач ввів число менше ста – попросити ввести ще раз, і таке інше. Якщо користувач вводить більше ста, текст або цикл закінчує всі ітерації, то функція виводить в консоль останній введення користувача і завершує функцію.


function getNumber() {
	let attempts = 0; // Лічильник спроб
	while (attempts < 10) { // Максимум 10 спроб
		 let userInput = prompt("Введіть число більше 100:"); // Запитуємо число
		 let number = parseInt(userInput); // Перетворюємо введення в число

		 if (number > 100) { // Якщо число більше 100
			  console.log("Ви ввели число більше 100:", number); // Виводимо останнє введене число
			  return; // Завершуємо функцію
		 } else {
			  alert("Число має бути більше 100. Спробуйте ще раз!"); // Повідомляємо користувача, якщо число менше 100
		 }

		 attempts++; // Збільшуємо лічильник спроб
	}

	console.log("Ви не ввели число більше 100 за 10 спроб."); // Якщо спроб більше 10, виводимо повідомлення
}

getNumber(); // Викликаємо функцію